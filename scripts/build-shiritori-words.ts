/**
 * Build the Shiritori dictionary from SCOWL (Spell Checking Oriented Word
 * Lists, size 60). Run it by hand when the list should change; the output is
 * committed, so a normal build never needs the SCOWL download.
 *
 *   bun scripts/build-shiritori-words.ts <scowl-dir>/final
 *
 * Only the common-word files up to level 60 are read. Proper nouns, upper-case
 * entries, abbreviations, contractions and anything under three letters are
 * dropped, so what is left is lower-case a-z words.
 */
import fs from 'node:fs';
import path from 'node:path';

const LEVELS = [10, 20, 35, 40, 50, 55, 60];
const FAMILIES = ['english-words', 'american-words'];

// Words SCOWL size 60 lacks but players use. Kept here so a rebuild does not lose them.
const EXTRA_WORDS = ['yack', 'yacked', 'yacking', 'yacks'];

const dir = process.argv[2];
if (!dir || !fs.existsSync(dir)) {
	console.error('usage: bun scripts/build-shiritori-words.ts <scowl-dir>/final');
	process.exit(1);
}

const words = new Set<string>();
for (const family of FAMILIES) {
	for (const level of LEVELS) {
		const file = path.join(dir, `${family}.${level}`);
		if (!fs.existsSync(file)) continue;
		for (const line of fs.readFileSync(file, 'latin1').split('\n')) {
			if (/^[a-z]{3,}$/.test(line)) words.add(line);
		}
	}
}

for (const w of EXTRA_WORDS) words.add(w);
const sorted = [...words].sort();
const out = path.resolve(import.meta.dirname, '../src/lib/server/shiritori-words.generated.ts');
fs.writeFileSync(
	out,
	`// Generated by scripts/build-shiritori-words.ts from SCOWL 2020.12.07, size 60.
// SCOWL is Copyright 2000-2018 Kevin Atkinson, used under its permissive licence.
// Do not edit by hand.
export const SHIRITORI_WORDS = \`${sorted.join('\n')}\`;
`
);
console.log(`${sorted.length} words -> ${path.relative(process.cwd(), out)}`);
