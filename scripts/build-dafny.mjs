// Verify each dafny/*.dfy listed below, compile it to JS, and wrap the CommonJS output as an ES
// module under src/lib/server/generated/. Needs `dafny` (4.11) on PATH.
// Usage: node scripts/build-dafny.mjs [FeatureAccess|WebhookGate]   (no argument builds all)
import { execFileSync } from 'node:child_process';
import { mkdtempSync, readFileSync, writeFileSync, rmSync, mkdirSync } from 'node:fs';
import { join } from 'node:path';
import { homedir } from 'node:os';

const MODULES = [
	{ dfy: 'FeatureAccess', out: 'feature-access-core.js', module: 'FeatureAccessCore' },
	{ dfy: 'WebhookGate', out: 'webhook-gate-core.js', module: 'WebhookGateCore' },
];

const root = new URL('..', import.meta.url).pathname;
const only = process.argv[2];

for (const m of MODULES.filter((x) => !only || x.dfy === only)) {
	const work = mkdtempSync(join(process.env.TMPDIR || join(homedir(), '.tmp'), 'dafny-'));
	try {
		execFileSync(
			'dafny',
			['build', '--target:js', join(root, `dafny/${m.dfy}.dfy`), '--output', join(work, 'out')],
			{
				stdio: ['ignore', 'inherit', 'inherit'],
				env: { ...process.env, NODE_PATH: join(root, 'node_modules') }
			}
		);
		const js = readFileSync(join(work, 'out.js'), 'utf8')
			.replace("const BigNumber = require('bignumber.js');", "import BigNumber from 'bignumber.js';")
			.replace(/\nlet _module = \(function\(\) \{[\s\S]*$/, '\n');
		if (js.includes('require(')) throw new Error('unexpected require() left in Dafny output');
		const out = join(root, 'src/lib/server/generated');
		mkdirSync(out, { recursive: true });
		writeFileSync(
			join(out, m.out),
			`// @ts-nocheck\n// GENERATED by scripts/build-dafny.mjs from dafny/${m.dfy}.dfy. Do not edit.\n${js}\nexport { _dafny, ${m.module} };\n`
		);
	} finally {
		rmSync(work, { recursive: true, force: true });
	}
}
